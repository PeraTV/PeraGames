  function languageFor(locale) {
    return /^pt(?:[-_]|$)/i.test(locale || 'pt-BR') ? 'pt-BR' : 'en';
  }

  function translator(locale) {
    const useEnglish = languageFor(locale) === 'en';
    return (message, values = {}) => {
      if (typeof message !== 'string') return message;
      const template = useEnglish && Object.hasOwn(english, message) ? english[message] : message;
      return template.replace(/\{(\w+)\}/g, (token, key) => Object.hasOwn(values, key) ? values[key] : token);
    };
  }

  const api = { languageFor, translator, messages: Object.keys(english) };
  if (typeof module !== 'undefined') module.exports = api;
  else window.peraLanguage = api;
